  function tx(text, lang){ const o = tr(text, lang); return o == null ? text : o; }
  function tr(text, lang){
    if(lang === 'ru') return text;
    const i = lang === 'ky' ? 0 : 1;
    const hit = DICT[text];
    if(hit) return hit[i];
    for(const [re, fn] of RULES){
      const m = text.match(re);
      if(m) return fn(m)[i];
    }
    return null;
  }

  let lang = (() => {
    const q = new URLSearchParams(location.search).get('lang');
    if(LANGS.includes(q)){ try{ localStorage.setItem(STORE, q); }catch(e){} return q; }
    try{ const s = localStorage.getItem(STORE); if(LANGS.includes(s)) return s; }catch(e){}
    return 'ru';
  })();

  const SKIP = new Set(['SCRIPT', 'STYLE', 'TEXTAREA', 'CODE']);
  const ORIG = new WeakMap();   // узел → исходный русский текст
  let busy = false;

  function translateText(node){
    let ru = ORIG.get(node);
    const cur = node.nodeValue;
    // текст поменял код страницы — запоминаем новый исходник
    if(ru === undefined || (node.__akSet !== cur)) { ru = cur; ORIG.set(node, ru); }
    const core = ru.trim();
    if(!core || !/[А-Яа-яЁё]/.test(core)) return;
    const out = tr(core.replace(/\u00a0/g, ' '), lang);
    const val = out == null ? ru : ru.replace(core, out);
    if(cur !== val){ node.nodeValue = val; }
    node.__akSet = node.nodeValue;
  }
  function translateAttrs(el){
    for(const a of ['placeholder', 'title', 'aria-label']){
      if(!el.hasAttribute || !el.hasAttribute(a)) continue;
      const key = 'akRu_' + a;
      if(el.dataset[key] === undefined || el.dataset[key + 'Set'] !== el.getAttribute(a)) el.dataset[key] = el.getAttribute(a);
      const ru = el.dataset[key];
      const out = /[А-Яа-яЁё]/.test(ru) ? tr(ru.trim(), lang) : null;
      el.setAttribute(a, out == null ? ru : out);
      el.dataset[key + 'Set'] = el.getAttribute(a);
    }
  }
  function walk(root){
    if(!root) return;
    if(root.nodeType === 3){ if(!(root.parentNode && SKIP.has(root.parentNode.nodeName))) translateText(root); return; }
    if(root.nodeType !== 1 || SKIP.has(root.nodeName) || root.hasAttribute('data-no-i18n')) return;
    translateAttrs(root);
    for(const c of root.childNodes) walk(c);
  }
  function applyAll(){
    busy = true;
    document.documentElement.lang = lang;
    walk(document.body);
    document.querySelectorAll('[data-lang]').forEach(el => el.hidden = el.getAttribute('data-lang') !== lang);
    document.querySelectorAll('.ak-lang button').forEach(b => b.classList.toggle('on', b.dataset.l === lang));
    busy = false;
  }

